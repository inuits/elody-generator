/**
 * The generated bundles go to the cluster through the client's Helm values
 * repository: `elody-ui analytics values` writes them as superset.bundles in
 * one values file (common/elody.yaml), between markers, and leaves the rest
 * of the file as it is. The chart mounts each bundle for elody-superset.
 */
import { spawnSync } from "child_process";
import { describe, expect, it } from "vitest";
import { bundleValues } from "../src/analytics/values.js";

const bundles = new Map([
  ["sla", new Map([["manifest.json", '{\n  "requires": []\n}\n'], ["clickhouse/001_sla.sql", "-- one\nCREATE DATABASE IF NOT EXISTS sla;\n"]])],
]);
const BEGIN = "# >>> generated by `elody-ui analytics values`: do not edit";
const END = "# <<< generated by `elody-ui analytics values`";

describe("analytics values", () => {
  it("writes the bundles as literal blocks under superset.bundles, files sorted", () => {
    const text = bundleValues("", bundles, "elody-declarations clients/podiumnet/analytics");
    expect(text).toBe(
      [
        BEGIN,
        "# from elody-declarations clients/podiumnet/analytics",
        "superset:",
        "  bundles:",
        "    sla:",
        '      "clickhouse/001_sla.sql": |',
        "        -- one",
        "        CREATE DATABASE IF NOT EXISTS sla;",
        '      "manifest.json": |',
        "        {",
        '          "requires": []',
        "        }",
        END,
        "",
      ].join("\n"),
    );
  });

  it("keeps the rest of the file and replaces its own block", () => {
    const first = bundleValues("global:\n  customer: x\n", bundles);
    expect(first.startsWith("global:\n  customer: x\n\n" + BEGIN)).toBe(true);
    const changed = new Map([["sla", new Map([["manifest.json", "{}\n"]])]]);
    const second = bundleValues(first + "\nrabbitmq:\n  enabled: true\n", changed);
    expect(second).toContain("global:\n  customer: x\n");
    expect(second).toContain("rabbitmq:\n  enabled: true\n");
    expect(second.split(BEGIN)).toHaveLength(2);
    expect(second).not.toContain("CREATE DATABASE");
    expect(second).toContain('      "manifest.json": |\n        {}\n');
  });

  it("refuses a file that has a superset key of its own, outside the block", () => {
    expect(() => bundleValues("superset:\n  enabled: true\n", bundles)).toThrow(/superset/);
  });

  it("keeps a file without a final newline exact, and refuses one that starts with a space", () => {
    const text = bundleValues("", new Map([["b", new Map([["x.sql", "SELECT 1;"]])]]));
    expect(text).toContain('      "x.sql": |-\n        SELECT 1;\n');
    expect(() => bundleValues("", new Map([["b", new Map([["x.sql", "  indented"]])]]))).toThrow(/x.sql/);
  });

  const python = spawnSync("python3", ["-c", "import yaml"]).status === 0;
  it.skipIf(!python)("reads back as the same files", () => {
    const files = new Map([["a.sql", "-- a\nSELECT 'x: y';\n\nSELECT 2;\n"], ["b.yaml", 'key: "value"\nlist:\n  - 1\n'], ["c", "no newline"]]);
    const text = bundleValues("global: {}\n", new Map([["sla", files]]));
    const read = spawnSync("python3", ["-c", "import json, sys, yaml; print(json.dumps(yaml.safe_load(sys.stdin)['superset']['bundles']['sla']))"], { input: text, encoding: "utf-8" });
    expect(read.stderr).toBe("");
    expect(JSON.parse(read.stdout)).toEqual(Object.fromEntries(files));
  });
});
