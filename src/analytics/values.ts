/**
 * The generated bundles in a client's Helm values (common/elody.yaml of its
 * values repository): superset.bundles.<name>.<path> is a file, written as a
 * literal block so a review reads the SQL and YAML as they are. The block
 * between the markers is this command's; the rest of the file is left alone,
 * and Helm merges superset.bundles with the environment's superset values.
 */
const BEGIN = "# >>> generated by `elody-ui analytics values`: do not edit";
const END = "# <<< generated by `elody-ui analytics values`";

/** A file as a literal block scalar under `key`, its lines indented by `indent`. */
function literal(key: string, content: string, indent: string): string {
  if (/^[ \t]/.test(content)) throw new Error(`${key} starts with white space: a literal block cannot hold it`);
  const chomp = content.endsWith("\n\n") ? "+" : content.endsWith("\n") ? "" : "-";
  const body = content.endsWith("\n") ? content.slice(0, -1) : content;
  const lines = body.split("\n").map((line) => (line ? `${indent}  ${line}` : ""));
  return `${indent}${JSON.stringify(key)}: |${chomp}\n${lines.join("\n")}\n`;
}

/** The values file with its generated block replaced by these bundles (name → path → content). */
export function bundleValues(existing: string, bundles: Map<string, Map<string, string>>, source?: string): string {
  const start = existing.indexOf(BEGIN);
  const end = existing.indexOf(END);
  const [before, after] = start >= 0 && end > start ? [existing.slice(0, start), existing.slice(end + END.length).replace(/^\n/, "")] : [existing, ""];
  if (/^superset:/m.test(before + after)) throw new Error("the values file has a superset key of its own: move it to the environment's file, superset.bundles is generated");
  let block = `${BEGIN}\n${source ? `# from ${source}\n` : ""}superset:\n  bundles:\n`;
  for (const [name, files] of [...bundles].sort(([a], [b]) => a.localeCompare(b))) {
    block += `    ${name}:\n`;
    for (const [path, content] of [...files].sort(([a], [b]) => a.localeCompare(b))) block += literal(path, content, "      ");
  }
  block += `${END}\n`;
  const head = before.trimEnd();
  return `${head ? `${head}\n\n` : ""}${block}${after ? `\n${after.trimStart()}` : ""}`;
}
